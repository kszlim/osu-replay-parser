"""Generate types from PyO3/Maturin and the runtime's Python dataclass contracts.

PyO3 cannot inspect Python-installed dataclass metadata or express overloaded
sequence slots. Dataclass types therefore refer to their existing annotated
Python contracts; a small sequence-slot overlay fills the remaining gaps.
Everything else comes from Maturin. No generated .pyi is edited by hand.
"""

from __future__ import annotations

import argparse
import ast
import dataclasses
import subprocess
import sys
import tempfile
from enum import Enum
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
HEADER = "# Generated by tools/generate_stubs.py; do not edit.\n"

# Overloads and in-place return types are not representable by PyO3's current
# introspection of protocol slots. Keep this small, explicit boundary here.
SEQUENCE_SLOTS = """
@overload
def __getitem__(self, index: int) -> ReplayEvent: ...
@overload
def __getitem__(self, index: slice) -> list[ReplayEvent]: ...
@overload
def __setitem__(self, index: int, value: ReplayEvent) -> None: ...
@overload
def __setitem__(self, index: slice, value: Iterable[ReplayEvent]) -> None: ...
def __delitem__(self, index: int | slice) -> None: ...
def __iter__(self) -> Iterator[ReplayEvent]: ...
def __iadd__(self, other: Iterable[ReplayEvent]) -> ReplayData: ...
def __imul__(self, count: int) -> ReplayData: ...
def __add__(self, other: list[ReplayEvent] | ReplayData) -> list[ReplayEvent]: ...
def __radd__(self, other: list[ReplayEvent]) -> list[ReplayEvent]: ...
def __mul__(self, count: int) -> list[ReplayEvent]: ...
def __rmul__(self, count: int) -> list[ReplayEvent]: ...
"""


def write(path, source, check):
    source = HEADER + source.strip() + "\n"
    source = subprocess.check_output(
        ["ruff", "check", "--fix", "--stdin-filename", str(path), "-"],
        input=source,
        text=True,
        cwd=ROOT,
    )
    source = subprocess.check_output(
        ["ruff", "format", "--stdin-filename", str(path), "-"],
        input=source,
        text=True,
        cwd=ROOT,
    )
    if check:
        if not path.exists() or path.read_text() != source:
            raise SystemExit(
                f"Stale stub: {path.relative_to(ROOT)}; run uv run python tools/generate_stubs.py"
            )
    else:
        path.write_text(source)


def generate(raw, check):
    import osrparse
    from osrparse import utils

    tree = ast.parse(raw)
    enums = {
        name
        for name in osrparse.__all__
        if isinstance(getattr(utils, name, None), type)
        and issubclass(getattr(utils, name), Enum)
    }
    sequence_slots = ast.parse(SEQUENCE_SLOTS).body
    slot_names = {node.name for node in sequence_slots}
    for position, node in enumerate(tree.body):
        if not isinstance(node, ast.ClassDef):
            continue
        public = getattr(osrparse, node.name, None)
        if public is not None and dataclasses.is_dataclass(public):
            # These classes already have annotated Python contracts. Re-export
            # those types rather than duplicating fields and constructors here.
            tree.body[position] = ast.ImportFrom(
                module=public.__module__,
                names=[ast.alias(name=node.name, asname=node.name)],
                level=0,
            )
        elif node.name == "ReplayData":
            node.bases = [ast.parse("MutableSequence[ReplayEvent]", mode="eval").body]
            for name in slot_names:
                assert hasattr(osrparse.ReplayData, name), name
            for method in node.body:
                if getattr(method, "name", "") in {
                    "__eq__",
                    "__ne__",
                    "__lt__",
                    "__le__",
                    "__gt__",
                    "__ge__",
                }:
                    method.returns = ast.Name(id="bool", ctx=ast.Load())
            node.body = [
                method
                for method in node.body
                if getattr(method, "name", "") not in slot_names
            ] + sequence_slots
    imports = (
        """from collections.abc import Callable, Iterable, Iterator, MutableSequence
from datetime import datetime
from typing import Any, overload
"""
        + f"from osrparse.utils import {', '.join(sorted(enums))}\n"
    )
    tree.body[:0] = ast.parse(imports).body
    tree.body.sort(key=lambda node: not isinstance(node, (ast.Import, ast.ImportFrom)))
    ast.fix_missing_locations(tree)
    write(ROOT / "osrparse/_native.pyi", ast.unparse(tree), check)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # Install the matching extension before reading Python-installed contracts.
    subprocess.run(
        ["maturin", "develop", "--release", "--locked"], cwd=ROOT, check=True
    )
    with tempfile.TemporaryDirectory(prefix="osrparse-stubs-") as directory:
        subprocess.run(
            [
                "maturin",
                "generate-stubs",
                "--out",
                directory,
                "--profile",
                "release",
                "--locked",
                "-i",
                sys.executable,
            ],
            cwd=ROOT,
            check=True,
        )
        generate((Path(directory) / "osrparse/_native.pyi").read_text(), args.check)


if __name__ == "__main__":
    main()
